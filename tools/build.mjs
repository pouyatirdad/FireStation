// Builds the game into a single, self-contained index.html.
//
// ES modules do not load from file://, and the game must open by double-click.
// This bundles src/ into one classic <script> (each module wrapped in a private
// closure, imports resolved from a small registry) and inlines styles/game.css.
//
//   node tools/build.mjs
//
// The script is deliberately dependency-free and only understands the module
// syntax this project uses: named imports, `import * as ns`, and exports of
// functions, consts, classes and export lists. Rebuild after editing src/.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const entry = 'src/main.js';

const modules = new Map();
const order = [];

const posix = (p) => p.split(path.sep).join('/');
const resolveFrom = (from, spec) => posix(path.posix.normalize(path.posix.join(path.posix.dirname(from), spec)));

function load(file) {
  if (modules.has(file)) return;
  const full = path.join(root, file);
  let code = fs.readFileSync(full, 'utf8').replace(/^\uFEFF/, '');
  const imports = [];
  const exports = [];

  code = code.replace(
    /^import\s+\*\s+as\s+([A-Za-z0-9_$]+)\s+from\s+['"]([^'"]+)['"];?[ \t]*$/gm,
    (line, ns, spec) => {
      imports.push({ ns, spec: resolveFrom(file, spec) });
      return '';
    },
  );

  code = code.replace(
    /^import\s+\{([\s\S]*?)\}\s+from\s+['"]([^'"]+)['"];?[ \t]*$/gm,
    (line, names, spec) => {
      const list = names
        .split(',')
        .map((n) => n.trim())
        .filter(Boolean)
        .map((n) => n.replace(/\s+as\s+/, ': '));
      imports.push({ names: list, spec: resolveFrom(file, spec) });
      return '';
    },
  );

  code = code.replace(
    /^export\s+(function|const|let|class)\s+([A-Za-z0-9_$]+)/gm,
    (line, kind, name) => {
      exports.push(name);
      return `${kind} ${name}`;
    },
  );

  code = code.replace(/^export\s*\{([^}]*)\};?[ \t]*$/gm, (line, names) => {
    for (const name of names.split(',')) {
      const clean = name.trim();
      if (clean) exports.push(clean);
    }
    return '';
  });

  if (/^\s*(import|export)\b/m.test(code)) {
    throw new Error(`Unsupported module syntax left in ${file}`);
  }

  modules.set(file, { imports, exports, code });

  for (const imp of imports) load(imp.spec);
  order.push(file);
}

load(entry);

let bundle = '(function () {\n"use strict";\nconst __m = {};\n';
for (const file of order) {
  const mod = modules.get(file);
  bundle += `\n// ---- ${file} ----\n`;
  bundle += `__m[${JSON.stringify(file)}] = (function () {\n`;
  for (const imp of mod.imports) {
    if (imp.ns) bundle += `const ${imp.ns} = __m[${JSON.stringify(imp.spec)}];\n`;
    else bundle += `const { ${imp.names.join(', ')} } = __m[${JSON.stringify(imp.spec)}];\n`;
  }
  bundle += `${mod.code}\n`;
  bundle += `return { ${mod.exports.join(', ')} };\n})();\n`;
}
bundle += '})();\n';

if (bundle.includes('</script')) {
  throw new Error('Bundle contains a literal </script sequence');
}

const css = fs.readFileSync(path.join(root, 'styles', 'game.css'), 'utf8').replace(/^\uFEFF/, '');
const htmlPath = path.join(root, 'index.html');
const html = fs
  .readFileSync(htmlPath, 'utf8')
  .replace(/^\uFEFF/, '')
  .replace(/^<!-- Generated by tools\/build\.mjs[^\n]*-->\n/m, '');

const styleBlock = `<style>\n${css}\n</style>`;
const scriptBlock = `<script>\n${bundle}</script>`;

let built = html
  .replace(
    /(<!-- build:css:start -->)[\s\S]*?(<!-- build:css:end -->)/,
    (match, start, end) => `${start}\n${styleBlock}\n${end}`,
  )
  .replace(
    /(<!-- build:js:start -->)[\s\S]*?(<!-- build:js:end -->)/,
    (match, start, end) => `${start}\n${scriptBlock}\n${end}`,
  );

if (!built.includes('<style>') || !built.includes('__m[')) {
  throw new Error('Build markers missing from index.html');
}

// A generated-file banner, kept out of the way of the doctype.
const banner = '<!-- Generated by tools/build.mjs. Edit src/ and styles/, then rebuild. -->\n';
built = built.replace('<!doctype html>\n', `<!doctype html>\n${banner}`);

fs.writeFileSync(htmlPath, built, 'utf8');

const kb = (n) => `${(n / 1024).toFixed(1)} KB`;
console.log(`bundled ${order.length} modules (${kb(bundle.length)}) + CSS into index.html (${kb(built.length)})`);
